void SetOpen(bool value) {
    if (value && cheat_open) {
        return;
    }
    if (menu_open.exchange(value) == value) {
        return;
    }
    ImGui::GetIO().MouseDrawCursor = value;
    if (value) {
        requested_tab = DcpSettings::Get().menu_tab;
    }
    if (!value && dirty) {
        dirty = false;
        DcpSettings::Save();
    }
}

