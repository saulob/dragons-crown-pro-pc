static int signature_matches_at(const unsigned char *image, uint64_t at, const DcpResolutionSignature *signature) {
    for (unsigned i = 0; i < signature->length; ++i)
        if (signature->compare[i] && image[at + i] != signature->pattern[i]) return 0;
    return 1;
}

static int find_signature(const unsigned char *image, uint64_t image_size, const DcpResolutionSignature *signature,
                          uint64_t *at) {
    uint64_t anchor = 0;
    if (image_size < signature->length) return 0;
    while (anchor < signature->length && !signature->compare[anchor]) ++anchor;
    if (anchor == signature->length) return 0;
    const uint64_t last = image_size - signature->length;
    int matches = 0;
    uint64_t start = 0;
    while (start <= last) {
        const unsigned char *hit =
            memchr(image + start + anchor, signature->pattern[anchor], (size_t)(last + anchor - start + 1));
        if (!hit) break;
        const uint64_t candidate = (uint64_t)(hit - image) - anchor;
        if (signature_matches_at(image, candidate, signature)) {
            if (matches == 0) *at = candidate;
            if (++matches == 2) break;
        }
        start = candidate + 1;
    }
    return matches;
}

static int site_bytes_hold(const unsigned char *image, uint64_t image_size, uint64_t site,
                           const DcpResolutionSignature *signature) {
    if (site + signature->opcode_length + 4 > image_size) return 0;
    if (memcmp(image + site, signature->opcode, signature->opcode_length)) return 0;
    uint32_t value;
    memcpy(&value, image + site + signature->opcode_length, sizeof(value));
    return value == signature->value;
}

static int sites_overlap(const DcpResolutionSignature *signatures, const DcpResolutionSignatureResult *results,
                         size_t count) {
    for (size_t i = 0; i < count; ++i)
        for (size_t j = i + 1; j < count; ++j) {
            const uint64_t a = results[i].offset;
            const uint64_t b = results[j].offset;
            if (a < b + signatures[j].opcode_length + 4 && b < a + signatures[i].opcode_length + 4) return 1;
        }
    return 0;
}

int dcp_find_resolution_sites(const unsigned char *image, uint64_t image_size, const DcpResolutionSignature *signatures,
                              size_t count, DcpResolutionSite *sites, DcpResolutionSignatureResult *results) {
    int complete = count > 0;
    for (size_t i = 0; i < count; ++i) {
        uint64_t at = 0;
        const DcpResolutionSignature *signature = &signatures[i];
        results[i].matches = find_signature(image, image_size, signature, &at);
        results[i].offset = (uint32_t)(at + signature->lead);
        results[i].valid = results[i].matches == 1 && site_bytes_hold(image, image_size, results[i].offset, signature);
        complete = complete && results[i].valid;
    }
    if (!complete || sites_overlap(signatures, results, count)) return 0;
    for (size_t i = 0; i < count; ++i) {
        sites[i].offset = results[i].offset;
        sites[i].opcode_length = signatures[i].opcode_length;
        memcpy(sites[i].opcode, signatures[i].opcode, sizeof(sites[i].opcode));
        sites[i].value = signatures[i].value;
        sites[i].height = signatures[i].height;
    }
    return 1;
}

static void print_expected_bytes(const DcpResolutionSignature *signature) {
    for (unsigned i = 0; i < signature->opcode_length; ++i) printf("%02x ", signature->opcode[i]);
    for (unsigned i = 0; i < 4; ++i) printf("%02x%s", (signature->value >> (8 * i)) & 0xff, i < 3 ? " " : "");
}

void dcp_probe_render_sites(const unsigned char *image, uint64_t image_size, const char *label) {
    const size_t count = DCP_CUSA10209_102_SIGNATURE_COUNT;
    DcpResolutionSignatureResult results[DCP_CUSA10209_102_SIGNATURE_COUNT];
    DcpResolutionSite sites[DCP_CUSA10209_102_SIGNATURE_COUNT];
    const int complete =
        dcp_find_resolution_sites(image, image_size, dcp_cusa10209_102_signatures, count, sites, results);
    int validated = 0;
    for (size_t i = 0; i < count; ++i) {
        const DcpResolutionSignature *signature = &dcp_cusa10209_102_signatures[i];
        const char *dimension = signature->height ? "height" : "width";
        if (results[i].valid) {
            ++validated;
            printf("DEBUG_SAULO site %02zu %s %u: found at 0x%x, expected ", i, dimension, signature->value,
                   results[i].offset);
        } else if (results[i].matches == 0) {
            printf("DEBUG_SAULO site %02zu %s %u: not found, expected ", i, dimension, signature->value);
        } else if (results[i].matches > 1) {
            printf("DEBUG_SAULO site %02zu %s %u: ambiguous, expected ", i, dimension, signature->value);
        } else {
            printf("DEBUG_SAULO site %02zu %s %u: bytes differ at 0x%x, expected ", i, dimension, signature->value,
                   results[i].offset);
        }
        print_expected_bytes(signature);
        printf("\n");
    }
    printf("DEBUG_SAULO render resolution %s: sites %d/%zu validated, image 0x%llx, %s\n", label, validated, count,
           (unsigned long long)image_size,
           complete ? "complete set, not applied by this diagnostic" : "custom resolutions stay disabled");
}
